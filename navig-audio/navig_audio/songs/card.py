"""The song card: a song folder's ``README.md`` with YAML front matter, plus the facts read from
the folder itself (lyrics, master, takes, stems, video …) written into a generated block.

The front matter is the owner's; navig only adds keys it is given and never drops one it does not
know. The facts block (between ``FACTS_BEGIN`` and ``FACTS_END``) is navig's and is rewritten on
every refresh; everything else in the body is left exactly as it was.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any
from urllib.parse import quote

import yaml

STATUSES = ("idea", "draft", "lyrics", "demo", "recorded", "mixed", "mastered", "released")
CARD = "README.md"
FACTS_BEGIN = "<!-- song:facts:begin — generated by `navig audio songs card`; edit above or below -->"
FACTS_END = "<!-- song:facts:end -->"
FIELD_ORDER = ("type", "id", "title", "status", "release", "year", "written", "recorded", "published", "track",
               "lang", "master",
               "soundcloud", "session", "beat", "aka")

AUDIO = {".mp3", ".wav", ".m4a", ".flac", ".aif", ".aiff", ".ogg", ".opus"}
VIDEO = {".mp4", ".mov", ".mkv", ".webm", ".avi"}
IMAGE = {".jpg", ".jpeg", ".png", ".webp", ".gif", ".psd"}
# a lyric file is tagged <lang>[-<year>]--<slug>.md (ru--odin.md, fr-2019--void.md, xx--…)
LYRIC = re.compile(r"^[a-z]{2}(?:/[a-z]{2})?(?:-\d{4})?--.+\.md$")
_FRONT = re.compile(r"\A---\r?\n(.*?)\r?\n---\r?\n?", re.S)


class SongError(ValueError):
    """A card navig cannot read or write as asked."""


@dataclass
class Facts:
    lyrics: list[str] = field(default_factory=list)
    transcripts: list[str] = field(default_factory=list)
    master: str | None = None
    versions: list[str] = field(default_factory=list)  # other audio at the top of the folder
    takes: int = 0
    stems: list[str] = field(default_factory=list)
    beat: list[str] = field(default_factory=list)
    video: int = 0
    art: int = 0
    sfx: int = 0
    sessions: list[str] = field(default_factory=list)  # .sesx kept inside the folder

    def as_dict(self) -> dict[str, Any]:
        return dict(self.__dict__)


@dataclass
class Song:
    folder: Path
    meta: dict[str, Any]
    body: str
    facts: Facts

    def get(self, key: str, default: Any = None) -> Any:
        return self.meta.get(key, default)

    @property
    def title(self) -> str:
        return str(self.meta.get("title") or self.folder.name)

    @property
    def status(self) -> str:
        return str(self.meta.get("status") or "")


def _files(d: Path, exts: set[str] | None = None) -> list[Path]:
    if not d.is_dir():
        return []
    return sorted(f for f in d.rglob("*") if f.is_file() and (exts is None or f.suffix.lower() in exts))


def _pick_master(top: list[Path], named: str | None) -> Path | None:
    if named:
        for f in top:
            if f.name == named:
                return f
    if not top:
        return None

    def rank(f: Path) -> tuple:
        n = f.name.lower()
        return ("final" not in n, "master" not in n, f.suffix.lower() != ".wav", -f.stat().st_size)

    return sorted(top, key=rank)[0]


def inspect_folder(folder: Path, master: str | None = None) -> Facts:
    """What the folder holds. ``master`` (the card's ``master:``) wins over the guess."""
    folder = Path(folder)
    top = [f for f in folder.iterdir() if f.is_file()] if folder.is_dir() else []
    lyr = sorted(f.name for f in top if LYRIC.match(f.name))
    audio = [f for f in top if f.suffix.lower() in AUDIO]
    m = _pick_master(audio, master)
    sub = {d.name.lower(): d for d in folder.iterdir() if d.is_dir()} if folder.is_dir() else {}
    return Facts(
        lyrics=[n for n in lyr if not n.endswith("--transcript.md")],
        transcripts=[n for n in lyr if n.endswith("--transcript.md")],
        master=m.name if m else None,
        versions=sorted(f.name for f in audio if f is not m),
        takes=len(_files(sub["takes"], AUDIO)) if "takes" in sub else 0,
        stems=[f.stem for f in _files(sub["stems"], AUDIO)] if "stems" in sub else [],
        beat=[f.name for f in _files(sub["beat"], AUDIO)] if "beat" in sub else [],
        video=sum(1 for f in top if f.suffix.lower() in VIDEO) + (len(_files(sub["video"], VIDEO)) if "video" in sub else 0),
        art=sum(1 for f in top if f.suffix.lower() in IMAGE) + (len(_files(sub["art"], IMAGE)) if "art" in sub else 0),
        sfx=len(_files(sub["sfx"], AUDIO)) if "sfx" in sub else 0,
        sessions=[f.relative_to(folder).as_posix() for f in _files(folder, {".sesx"}) if "Backup" not in f.parts],
    )


def _split(text: str) -> tuple[dict[str, Any] | None, str]:
    m = _FRONT.match(text)
    if not m:
        return None, text
    try:
        meta = yaml.safe_load(m.group(1)) or {}
    except yaml.YAMLError as exc:
        raise SongError(f"front matter is not valid YAML: {exc}") from exc
    if not isinstance(meta, dict):
        raise SongError("front matter must be a mapping")
    return meta, text[m.end():]


def read_card(folder: Path) -> Song | None:
    """The song in ``folder``, or None when its README is not a song card."""
    card = Path(folder) / CARD
    if not card.is_file():
        return None
    meta, body = _split(card.read_text(encoding="utf-8-sig"))
    if not meta or meta.get("type") != "song":
        return None
    return Song(folder=Path(folder), meta=meta, body=body, facts=inspect_folder(folder, meta.get("master")))


def scan(root: Path) -> list[Song]:
    """Every song card under ``root`` (hidden folders skipped), in path order."""
    root = Path(root)
    songs = []
    for card in sorted(root.rglob(CARD)):
        rel = card.relative_to(root).parts
        if any(p.startswith(".") for p in rel[:-1]):
            continue
        try:
            s = read_card(card.parent)
        except SongError:
            continue
        if s:
            songs.append(s)
    return songs


def _link(name: str) -> str:
    return f"[{name}]({quote(name, safe='/-_.()')})"


def render_facts(f: Facts, meta: dict[str, Any]) -> str:
    def or_dash(v: Any) -> str:
        return str(v) if v else "—"

    rows = [
        ("Master", f"`{f.master}`" if f.master else "—"),
        ("Lyrics", " · ".join(_link(n) for n in f.lyrics) or "—"),
        ("Transcript", " · ".join(_link(n) for n in f.transcripts) or "—"),
        ("Other versions", " · ".join(f"`{n}`" for n in f.versions) or "—"),
        ("Takes", f"{f.takes} in `takes/`" if f.takes else "—"),
        ("Stems", ", ".join(f.stems) or "—"),
        ("Beat", " · ".join(f"`{n}`" for n in f.beat) or or_dash(meta.get("beat"))),
        ("Video", or_dash(f.video)),
        ("Art", or_dash(f.art)),
        ("SFX", or_dash(f.sfx)),
        ("Session", " · ".join(f"`{s}`" for s in f.sessions) or or_dash(meta.get("session"))),
    ]
    lines = [FACTS_BEGIN, "", "| | |", "|---|---|"]
    lines += [f"| {k} | {v} |" for k, v in rows]
    return "\n".join(lines + ["", FACTS_END])


def _ordered(meta: dict[str, Any]) -> dict[str, Any]:
    out = {k: meta[k] for k in FIELD_ORDER if k in meta and meta[k] not in (None, "")}
    out.update({k: v for k, v in meta.items() if k not in out and v not in (None, "")})
    return out


def write_card(folder: Path, updates: dict[str, Any] | None = None, *, dry_run: bool = False) -> tuple[Path, str]:
    """Create or refresh the card. Returns (path, the text written or that would be written).

    An existing README without front matter keeps its text, below the facts block. A card's own
    keys are kept; ``updates`` adds or changes only the keys it carries (None/"" are ignored).
    """
    folder = Path(folder)
    if not folder.is_dir():
        raise SongError(f"not a folder: {folder}")
    card = folder / CARD
    meta: dict[str, Any] = {}
    body = ""
    if card.is_file():
        old_meta, body = _split(card.read_text(encoding="utf-8-sig"))
        if old_meta is not None:
            if old_meta.get("type") not in (None, "song"):
                raise SongError(f"{card} is a {old_meta.get('type')!r} card, not a song")
            meta = dict(old_meta)
    meta.update({k: v for k, v in (updates or {}).items() if v not in (None, "")})
    meta["type"] = "song"
    h1 = re.search(r"^# (.+)$", body, re.M)
    meta.setdefault("title", h1.group(1).strip() if h1 else folder.name)
    status = meta.get("status")
    if status and status not in STATUSES:
        raise SongError(f"unknown status {status!r} — one of: {', '.join(STATUSES)}")
    facts = render_facts(inspect_folder(folder, meta.get("master")), meta)
    if FACTS_BEGIN in body and FACTS_END in body:
        head, rest = body.split(FACTS_BEGIN, 1)
        tail = rest.split(FACTS_END, 1)[1]
        body = head + facts + tail
    else:
        stripped = body.strip("\n")
        if not stripped.startswith("# "):
            stripped = f"# {meta['title']}\n\n" + stripped if stripped else f"# {meta['title']}"
        heading, _, rest = stripped.partition("\n")
        body = f"{heading}\n\n{facts}\n" + (f"\n{rest.strip()}\n" if rest.strip() else "")
    front = yaml.safe_dump(_ordered(meta), allow_unicode=True, sort_keys=False, width=1000).strip()
    text = f"---\n{front}\n---\n{body if body.startswith(chr(10)) else chr(10) + body}"
    if not dry_run:
        card.write_text(text, encoding="utf-8")
    return card, text
