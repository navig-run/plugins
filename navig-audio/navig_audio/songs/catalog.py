"""The catalog, generated from the song cards — a Markdown view and a CSV mirror.

The Markdown goes between two markers in a file the owner also edits by hand
(``songs/CATALOG.md``): everything outside the markers is theirs and is never touched.
"""

from __future__ import annotations

import csv
import os
import re
from collections import Counter
from pathlib import Path
from urllib.parse import quote

from navig_audio.songs.card import STATUSES, Song

BEGIN = "<!-- songs:catalog:begin — generated by `navig audio songs catalog`; do not edit inside -->"
END = "<!-- songs:catalog:end -->"
CSV_COLUMNS = ("id", "title", "status", "release", "year", "written", "recorded", "published", "track", "lang",
               "folder", "master", "lyrics",
               "transcripts", "takes", "stems", "video", "session", "soundcloud")


def _rel(path: Path, base: Path) -> str:
    return os.path.relpath(path, base).replace(os.sep, "/")


def _year(s: Song) -> int:
    """The first 4-digit year the card states (``year``, else ``recorded``/``published``); 9999 when none."""
    for key in ("year", "recorded", "published", "written"):
        m = re.search(r"(19|20)\d\d", str(s.get(key) or ""))
        if m:
            return int(m.group(0))
    return 9999


def span(rows: list[Song], name: str = "") -> str:
    """' (2012–2019)' for a release's songs — nothing when unknown or already in its name."""
    known = sorted(y for y in (_year(s) for s in rows) if y != 9999)
    if not known:
        return ""
    text = str(known[0]) if known[0] == known[-1] else f"{known[0]}–{known[-1]}"
    return "" if text in name else f" ({text})"


def years(s: Song) -> str:
    """When the song was written / recorded / published, as far as the card knows."""
    parts = [f"{label} {s.get(key)}" for key, label in (("written", "✍"), ("recorded", "🎙"), ("published", "📤"))
             if s.get(key)]
    return " · ".join(parts) or str(s.get("year") or "—")


def _track(s: Song) -> int:
    try:
        return int(s.get("track"))
    except (TypeError, ValueError):
        return 999


def problems(songs: list[Song]) -> list[str]:
    """What a catalog check reports: unknown statuses, duplicate ids, recorded songs with no audio."""
    out = []
    ids = Counter(str(s.get("id")) for s in songs if s.get("id"))
    out += [f"id {i} is used by {n} songs" for i, n in ids.items() if n > 1]
    for s in songs:
        where = s.folder.as_posix()
        if s.status and s.status not in STATUSES:
            out.append(f"{where}: unknown status {s.status!r}")
        if not s.status:
            out.append(f"{where}: no status")
        recorded = s.status in STATUSES[STATUSES.index("demo"):] if s.status in STATUSES else False
        if recorded and not s.facts.master:
            out.append(f"{where}: {s.status} but no audio at the top of the folder")
    return out


def render_catalog(songs: list[Song], base: Path) -> str:
    """Markdown tables: one per release (by year), then unreleased songs by status."""
    base = Path(base)
    by_status = Counter(s.status or "?" for s in songs)
    summary = " · ".join(f"{st} {by_status[st]}" for st in reversed(STATUSES) if by_status.get(st))
    if by_status.get("?"):
        summary += f" · no status {by_status['?']}"
    lines = [BEGIN, "", f"**{len(songs)} songs** — {summary}", ""]

    def table(rows: list[Song], numbered: bool) -> list[str]:
        out = ["| # | Song | Years | Status | Lang | Lyrics | Master | Takes | Folder |",
               "|---|---|---|---|---|---|---|---|---|"]
        for s in rows:
            folder = _rel(s.folder, base)
            link = quote(folder + "/README.md", safe="/-_.()")
            lyr = len(s.facts.lyrics) + len(s.facts.transcripts)
            out.append(
                f"| {s.get('track', '') if numbered else ''} | [**{s.title}**]({link}) | {years(s)} | {s.status or '—'} | "
                f"{s.get('lang') or '—'} | {lyr or '—'} | {'✓' if s.facts.master else '—'} | "
                f"{s.facts.takes or '—'} | `{folder}/` |")
        return out

    releases: dict[str, list[Song]] = {}
    for s in songs:
        if s.get("release"):
            releases.setdefault(str(s.get("release")), []).append(s)
    for name, rows in sorted(releases.items(), key=lambda kv: (min(_year(s) for s in kv[1]), kv[0])):
        lines += [f"### {name}{span(rows, name)}", ""]
        lines += table(sorted(rows, key=lambda s: (_track(s), s.title)), True) + [""]
    loose = [s for s in songs if not s.get("release")]
    for st in reversed(STATUSES):
        rows = [s for s in loose if s.status == st]
        if rows:
            lines += [f"### Not released — {st}", ""] + table(sorted(rows, key=lambda s: s.title.lower()), False) + [""]
    other = [s for s in loose if s.status not in STATUSES]
    if other:
        lines += ["### No status", ""] + table(other, False) + [""]
    return "\n".join(lines + [END])


def write_catalog(songs: list[Song], md_path: Path, *, title: str = "Songs") -> Path:
    """Put the generated block into ``md_path`` (created if missing); the rest of the file stays."""
    md_path = Path(md_path)
    block = render_catalog(songs, md_path.parent)
    if md_path.is_file():
        text = md_path.read_text(encoding="utf-8-sig")
        if BEGIN in text and END in text:
            head, rest = text.split(BEGIN, 1)
            text = head + block + rest.split(END, 1)[1]
        else:
            text = text.rstrip("\n") + "\n\n" + block + "\n"
    else:
        text = f"# {title}\n\n{block}\n"
    md_path.write_text(text, encoding="utf-8")
    return md_path


def write_csv(songs: list[Song], csv_path: Path, base: Path) -> Path:
    """The machine mirror: one row per song card."""
    csv_path = Path(csv_path)
    csv_path.parent.mkdir(parents=True, exist_ok=True)
    with csv_path.open("w", encoding="utf-8-sig", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(CSV_COLUMNS)
        for s in songs:
            f = s.facts
            w.writerow([s.get("id", ""), s.title, s.status, s.get("release", ""), s.get("year", ""),
                        s.get("written", ""), s.get("recorded", ""), s.get("published", ""),
                        s.get("track", ""), s.get("lang", ""), _rel(s.folder, base), f.master or "",
                        " · ".join(f.lyrics), " · ".join(f.transcripts), f.takes, " · ".join(f.stems), f.video,
                        " · ".join(f.sessions) or s.get("session", ""), s.get("soundcloud", "")])
    return csv_path
