"""AI regeneration: new audio made FROM an existing recording — always labelled as new.

Unlike Audio Enhance (which filters the original and proves it is still the same
recording), everything here is GENERATED by a model. The original is never written;
outputs are new files with a provenance sidecar, and each carries a "how close to the
original" report that informs — it never certifies.

Operations (ElevenLabs, the account's existing key — every call uploads or bills, so
each run needs ``allow_cloud=True``):

* ``voice``      — speech-to-speech: the same words, timing and delivery in another voice.
* ``variations`` — N new takes of a sound or music cue at the source's length, from a
  description (measured locally; optionally heard by an AI) plus your direction. Only
  TEXT is sent to ElevenLabs for this one.
* ``replace``    — split into stems and change one: re-voice the vocals (timing kept),
  or generate a new drums / bass / other stem at the measured tempo, loudness-matched,
  remixed with the untouched stems.
"""

from __future__ import annotations

import asyncio
import hashlib
import io
import json
import logging
import shutil
import subprocess
import tempfile
import time
import zipfile
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Protocol

from navig_audio.enhance.analysis import AnalyzeError, AudioReport, analyze
from navig_audio.regenerate.description import Description, describe

logger = logging.getLogger(__name__)

OPS = ("voice", "variations", "replace")
STEMS_SIX = ("drums", "bass", "guitar", "piano", "vocals", "other")
SFX_MAX_S = 22.0   # ElevenLabs sound-generation accepts 0.5–22 s
MUSIC_MIN_S, MUSIC_MAX_S = 10.0, 300.0
MAX_VARIATIONS = 4


class RegenerateError(RuntimeError):
    """The request can't run (bad input, no consent, provider failure)."""


class Provider(Protocol):
    async def change_voice(self, src: Path, voice_id: str) -> bytes: ...
    async def sfx(self, prompt: str, duration_s: float) -> bytes: ...
    async def music(self, prompt: str, duration_s: float, *, instrumental: bool) -> bytes: ...
    async def stems(self, src: Path, *, six: bool) -> bytes: ...


class ElevenLabsProvider:
    """The account's ElevenLabs client (navig-generate) behind the Provider seam."""

    async def _with(self, fn):
        from navig_generate.tools.audio_generation import AudioGenerationConfig, AudioGenerator

        gen = AudioGenerator(AudioGenerationConfig(save_locally=False))
        try:
            return await fn(gen)
        finally:
            await gen.close()

    async def change_voice(self, src: Path, voice_id: str) -> bytes:
        return await self._with(lambda g: g.change_voice(src, voice_id))

    async def sfx(self, prompt: str, duration_s: float) -> bytes:
        res = await self._with(lambda g: g.generate(prompt, kind="sfx", duration_s=duration_s, save=False))
        return res.audio or b""

    async def music(self, prompt: str, duration_s: float, *, instrumental: bool) -> bytes:
        res = await self._with(lambda g: g.generate(prompt, kind="music", duration_s=duration_s, save=False,
                                                    force_instrumental=instrumental))
        return res.audio or b""

    async def stems(self, src: Path, *, six: bool) -> bytes:
        return await self._with(lambda g: g.separate_stems(src, stem_variation_id="six_stems_v1" if six else "two_stems_v1"))


@dataclass
class Take:
    path: str
    prompt: str
    similarity: dict[str, Any]


@dataclass
class RegenerateResult:
    op: str
    source: str
    source_sha256: str
    description: Description | None
    takes: list[Take] = field(default_factory=list)
    plan: dict[str, Any] = field(default_factory=dict)
    sidecar: str | None = None
    seconds: float = 0.0

    def to_dict(self) -> dict[str, Any]:
        return {
            "op": self.op, "source": self.source, "source_sha256": self.source_sha256, "generated": True,
            "description": self.description.to_dict() if self.description else None,
            "takes": [t.__dict__ for t in self.takes], "plan": self.plan, "sidecar": self.sidecar,
            "seconds": round(self.seconds, 2),
        }


# ── helpers ──────────────────────────────────────────────────────────


def _sha(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _ffmpeg(args: list[str], what: str) -> None:
    exe = shutil.which("ffmpeg")
    if not exe:
        raise RegenerateError("ffmpeg is not on PATH")
    proc = subprocess.run([exe, "-hide_banner", "-nostdin", "-y", "-v", "error", *args],  # noqa: S603
                          capture_output=True, timeout=900, check=False)
    if proc.returncode != 0:
        tail = proc.stderr.decode("utf-8", "replace").strip().splitlines()
        raise RegenerateError(f"ffmpeg failed on {what}: {tail[-1] if tail else 'no output'}")


def _new_name(src: Path, out_dir: Path, label: str, ext: str) -> Path:
    from navig_audio.enhance.engine import _SAFE_STEM, unique_path

    stem = _SAFE_STEM.sub("_", src.stem).strip(" .") or "audio"
    for _ in range(1000):
        cand = unique_path(out_dir / f"{stem[:100]}.regen-{label}{ext}")
        try:
            with cand.open("xb"):
                return cand
        except FileExistsError:
            continue
    raise RegenerateError(f"no free output name in {out_dir}")


def _write_take(data: bytes, src: Path, out_dir: Path, label: str, report: AudioReport, work: Path) -> Path:
    """Provider bytes (mp3 or wav) → a WAV at the source's rate and channel count."""
    if not data:
        raise RegenerateError("the provider returned no audio")
    raw = work / f"raw-{label}.bin"
    raw.write_bytes(data)
    dst = _new_name(src, out_dir, label, ".wav")
    try:
        _ffmpeg(["-i", str(raw), "-ar", str(report.sample_rate), "-ac", str(report.channels),
                 "-c:a", "pcm_s24le", str(dst)], f"the {label} take")
    except RegenerateError:
        dst.unlink(missing_ok=True)
        raise
    return dst


def similarity(source: AudioReport, take: Path) -> dict[str, Any]:
    """How close a NEW take is to the original — informative, never a pass/fail.

    Uses the Enhance verifier's measures (length, timing, events, tone, pitch) at the
    loosest tolerance and reports the values with a one-line reading.
    """
    from navig_audio.enhance.verify import verify

    try:
        v = verify(source, take, mode="cinematic", stages=[], true_peak_db=0.0, creative=True)
    except (AnalyzeError, ValueError) as exc:
        return {"error": str(exc)}
    by = {c.name: c.value for c in v.checks}
    keys = ("duration", "alignment", "envelope", "events_kept", "no_new_events", "tone", "pitch")
    out = {k: by.get(k) for k in keys if k in by}
    env = by.get("envelope")
    close = isinstance(env, (int, float)) and env >= 0.9
    out["reading"] = ("follows the original's shape closely" if close else
                      "a new take — similar in kind, different in detail")
    return out


def _run(coro):
    try:
        asyncio.get_running_loop()
    except RuntimeError:
        return asyncio.run(coro)
    raise RegenerateError("call regenerate() from a worker thread, not inside an event loop")


# ── the operations ───────────────────────────────────────────────────


def regenerate(
    src: Path | str,
    *,
    op: str,
    allow_cloud: bool,
    out_dir: Path | str | None = None,
    voice_id: str | None = None,
    direction: str = "",
    count: int = 2,
    stem: str | None = None,
    replace_with: str = "",
    use_ai_description: bool = False,
    category: str = "auto",
    provider: Provider | None = None,
    dry_run: bool = False,
    progress: Callable[[str, float], None] | None = None,
) -> RegenerateResult:
    """Make new audio from ``src``. Raises :class:`RegenerateError` with a readable reason."""
    t0 = time.monotonic()
    say = progress or (lambda _m, _f: None)
    path = Path(src).expanduser()
    if op not in OPS:
        raise RegenerateError(f"op must be one of {', '.join(OPS)}")
    try:
        report = analyze(path, category=category)
    except AnalyzeError as exc:
        raise RegenerateError(str(exc)) from exc
    digest = _sha(path)
    count = max(1, min(MAX_VARIATIONS, int(count)))

    plan: dict[str, Any] = {"op": op, "provider": "elevenlabs", "uploads_source": op in ("voice", "replace"),
                            "uploads_to_ai": use_ai_description}
    if op == "voice":
        if not voice_id:
            raise RegenerateError("choose a voice (voice_id) — `navig voice list-voices` shows yours")
        if report.category not in ("speech", "mixed") and category == "auto":
            raise RegenerateError(f"voice works on speech; this looks like {report.category} "
                                  "(use --category speech if it is a voice)")
        plan.update(voice_id=voice_id, seconds_billed=round(report.decoded_duration_s, 2))
    elif op == "variations":
        kind = "music" if report.category in ("music", "ambience") else "sfx"
        dur = (min(max(report.decoded_duration_s, 0.5), SFX_MAX_S) if kind == "sfx"
               else min(max(report.decoded_duration_s, MUSIC_MIN_S), MUSIC_MAX_S))
        plan.update(kind=kind, duration_s=round(dur, 2), count=count, direction=direction,
                    seconds_billed=round(dur * count, 2))
        if kind == "sfx" and report.decoded_duration_s > SFX_MAX_S:
            plan["note"] = f"sound effects are generated up to {SFX_MAX_S:.0f} s; the source is longer"
    else:  # replace
        if stem not in STEMS_SIX:
            raise RegenerateError(f"stem must be one of {', '.join(STEMS_SIX)}")
        if stem == "vocals" and not voice_id:
            raise RegenerateError("replacing the vocals re-voices them — choose a voice (voice_id)")
        if stem != "vocals" and not replace_with.strip():
            raise RegenerateError(f"say what the new {stem} should be (replace_with), e.g. 'lo-fi brushed kit'")
        plan.update(stem=stem, replace_with=replace_with, voice_id=voice_id,
                    seconds_billed=round(report.decoded_duration_s * (2 if stem != "vocals" else 1), 2))

    desc = None
    if op == "variations" or (op == "replace" and stem != "vocals"):
        if use_ai_description and not allow_cloud:
            raise RegenerateError("describing with AI uploads the file — allow cloud processing for this run")
        say("describing", 0.05)
        desc = describe(report, use_ai=use_ai_description and not dry_run)

    result = RegenerateResult(op=op, source=str(path), source_sha256=digest, description=desc, plan=plan)
    if dry_run:
        result.seconds = time.monotonic() - t0
        return result
    if not allow_cloud:
        raise RegenerateError("regeneration runs on ElevenLabs (uploads / bills) — allow cloud processing for this run")

    prov = provider or ElevenLabsProvider()
    dest = Path(out_dir).expanduser() if out_dir else path.parent
    dest.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="navig-regen-") as tmp:
        work = Path(tmp)
        if op == "voice":
            say("re-voicing", 0.3)
            data = _run(prov.change_voice(path, voice_id))
            take = _write_take(data, path, dest, "voice", report, work)
            result.takes.append(Take(str(take), f"voice {voice_id}", similarity(report, take)))
        elif op == "variations":
            prompt = f"{desc.text}. {direction.strip()}".strip(". ") if desc else direction
            plan["prompt"] = prompt
            for i in range(count):
                say(f"generating take {i + 1}/{count}", 0.2 + 0.6 * i / count)
                if plan["kind"] == "sfx":
                    data = _run(prov.sfx(prompt, plan["duration_s"]))
                else:
                    data = _run(prov.music(prompt, plan["duration_s"], instrumental=True))
                take = _write_take(data, path, dest, f"var{i + 1}", report, work)
                result.takes.append(Take(str(take), prompt, similarity(report, take)))
        else:
            take = _replace(path, report, stem, voice_id, replace_with, desc, prov, dest, work, plan, say)
            result.takes.append(Take(str(take), plan.get("prompt", ""), similarity(report, take)))
    if _sha(path) != digest:
        raise RegenerateError("the original changed while regenerating — outputs not trusted")
    result.seconds = time.monotonic() - t0
    side = Path(result.takes[0].path + ".regen.json")
    doc = result.to_dict()
    doc["note"] = "GENERATED audio — a new take made from the original, not a restoration of it."
    side.write_text(json.dumps(doc, ensure_ascii=False, indent=2), encoding="utf-8")
    result.sidecar = str(side)
    say("done", 1.0)
    return result


def _replace(path: Path, report: AudioReport, stem: str, voice_id: str | None, replace_with: str,
             desc: Description | None, prov: Provider, dest: Path, work: Path, plan: dict[str, Any],
             say: Callable[[str, float], None]) -> Path:
    say("separating stems", 0.15)
    six = stem != "vocals"
    blob = _run(prov.stems(path, six=six))
    stems_dir = work / "stems"
    stems_dir.mkdir()
    try:
        with zipfile.ZipFile(io.BytesIO(blob)) as z:
            for name in z.namelist():
                base = Path(name).name
                if base and not base.startswith(".") and Path(base).suffix.lower() in (".mp3", ".wav", ".flac"):
                    (stems_dir / base).write_bytes(z.read(name))
    except zipfile.BadZipFile as exc:
        raise RegenerateError("stem separation did not return a zip of stems") from exc
    files = {f.stem.lower(): f for f in stems_dir.iterdir()}
    target = next((f for k, f in files.items() if stem in k), None)
    if target is None:
        raise RegenerateError(f"no '{stem}' stem came back (got: {', '.join(sorted(files)) or 'nothing'})")
    others = [f for f in files.values() if f != target]
    plan["stems"] = sorted(files)

    new_stem = work / "new-stem.audio"
    if stem == "vocals":
        say("re-voicing the vocals", 0.45)
        new_stem.write_bytes(_run(prov.change_voice(target, voice_id)))
        plan["prompt"] = f"vocals re-voiced as {voice_id}"
    else:
        bpm_note = ""
        try:
            from navig_generate.media.beats import LOW_CONFIDENCE, detect

            grid = detect(path)
            if grid.confidence >= LOW_CONFIDENCE:
                bpm_note = f", {grid.bpm:.0f} BPM"
                plan["bpm"] = round(grid.bpm, 1)
        except Exception:  # noqa: BLE001 — tempo is a hint; a failed detection just omits it
            logger.debug("tempo detection failed", exc_info=True)
        prompt = f"isolated {stem} track only: {replace_with.strip()}{bpm_note}"
        if desc:
            prompt += f"; to sit under: {desc.measured}"
        plan["prompt"] = prompt
        say(f"generating new {stem}", 0.45)
        dur = min(max(report.decoded_duration_s, MUSIC_MIN_S), MUSIC_MAX_S)
        new_stem.write_bytes(_run(prov.music(prompt, dur, instrumental=True)))
    if not new_stem.stat().st_size:
        raise RegenerateError("the provider returned no audio for the new stem")

    say("matching loudness and remixing", 0.8)
    from navig_audio.mastering.loudness import measure

    old_lufs = measure(target).lufs
    new_lufs = measure(new_stem).lufs
    gain = (old_lufs - new_lufs) if old_lufs != float("-inf") and new_lufs != float("-inf") else 0.0
    plan["stem_gain_db"] = round(gain, 2)
    inputs: list[str] = []
    for f in [*others, new_stem]:
        inputs += ["-i", str(f)]
    n = len(others) + 1
    graph = (f"[{n - 1}:a]volume={gain:.2f}dB[ns];"
             + "".join(f"[{i}:a]" for i in range(n - 1)) + f"[ns]amix=inputs={n}:duration=first:normalize=0,"
             f"atrim=end={report.decoded_duration_s:.4f},aresample={report.sample_rate}[mix]")
    if not others:  # a two-stem split whose only other part is the target itself
        graph = f"[0:a]volume={gain:.2f}dB,aresample={report.sample_rate}[mix]"
    dst = _new_name(path, dest, f"replace-{stem}", ".wav")
    try:
        _ffmpeg([*inputs, "-filter_complex", graph, "-map", "[mix]", "-ac", str(report.channels),
                 "-c:a", "pcm_s24le", str(dst)], "the remix")
    except RegenerateError:
        dst.unlink(missing_ok=True)
        raise
    return dst
