"""Deterministic safety signals for automatic replies — no model is asked any of this.

Three questions, answered from headers and plain text only:

1. **Is this mail from a machine?** (``automated``) Mailing lists, bounces, auto-replies,
   other assistants, bulk senders, and our own outgoing mail. Answering a machine is how two
   auto-responders end up mailing each other forever, so any one signal is enough to skip.
2. **Did the sender's domain vouch for it?** (``authentication``) Gmail writes
   ``Authentication-Results``; DKIM or SPF passing *for the From domain* (DMARC alignment, or
   a dkim ``header.d``/``header.i`` that matches) is "pass". No header is "none", not "pass".
3. **Is this something a machine must never answer alone?** (``hard_exclusions``) Contracts,
   payments, bank details, loans and deposits, job offers, government and administrative mail,
   account recovery, credentials, security incidents, sensitive attachments, and requests for
   irreversible actions — in English, French and Russian. These are absolute: no policy, however
   configured, can turn one of these into an automatic send (:mod:`navig_email.policy`).
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from email.utils import parseaddr
from typing import Any

# ── 1. machines ────────────────────────────────────────────────────────────

_NOREPLY = re.compile(
    r"^(?:no[-_.]?reply|do[-_.]?not[-_.]?reply|donotreply|mailer[-_.]?daemon|postmaster|bounces?|"
    r"notifications?|notify|alerts?|automated|auto[-_.]?(?:reply|confirm)|system|robot|daemon)"
    r"(?:[+-].*)?@",
    re.IGNORECASE,
)
_AUTO_SUBJECT = re.compile(
    r"^(?:auto(?:matic)?[- ]?reply|out of (?:the )?office|absence|réponse automatique|"
    r"automatische antwort|автоответ|недоставлено|undeliverable|delivery status notification|"
    r"mail delivery (?:failed|subsystem)|returned mail|non remis)",
    re.IGNORECASE,
)


def headers_of(msg: dict[str, Any]) -> dict[str, str]:
    """Lowercased header name → value, from a shaped message's ``headers`` (or empty)."""
    raw = msg.get("headers") or {}
    return {str(k).lower(): str(v) for k, v in raw.items()} if isinstance(raw, dict) else {}


def automated(msg: dict[str, Any]) -> str:
    """Why *msg* looks machine-sent (``""`` when it looks like a person)."""
    h = headers_of(msg)
    sender = parseaddr(msg.get("from") or "")[1].lower()
    if h.get("x-navig-job"):
        return "sent by navig itself"
    auto = h.get("auto-submitted", "").strip().lower()
    if auto and auto != "no":
        return f"Auto-Submitted: {auto}"
    if h.get("list-id") or h.get("list-unsubscribe") or h.get("list-post"):
        return "mailing list"
    if h.get("precedence", "").strip().lower() in ("bulk", "list", "junk", "auto_reply"):
        return f"Precedence: {h['precedence']}"
    for k in ("x-autoreply", "x-autorespond", "x-auto-response-suppress", "x-autogenerated", "feedback-id"):
        if h.get(k):
            return k
    if h.get("return-path", "").strip() in ("<>", ""):
        if "return-path" in h:
            return "null Return-Path (a bounce)"
    if "multipart/report" in h.get("content-type", "").lower():
        return "delivery report"
    if sender and _NOREPLY.match(sender):
        return f"automated sender {sender}"
    if _AUTO_SUBJECT.match((msg.get("subject") or "").strip()):
        return "auto-reply subject"
    labels = set(msg.get("labels") or [])
    if labels & {"SPAM", "CATEGORY_PROMOTIONS", "CATEGORY_FORUMS", "CATEGORY_UPDATES", "CATEGORY_SOCIAL"}:
        return "Gmail category " + ",".join(sorted(labels & {"SPAM", "CATEGORY_PROMOTIONS", "CATEGORY_FORUMS",
                                                              "CATEGORY_UPDATES", "CATEGORY_SOCIAL"}))
    return ""


# ── 2. sender authentication ───────────────────────────────────────────────


def authentication(msg: dict[str, Any]) -> str:
    """``pass`` / ``fail`` / ``none`` for the From domain."""
    h = headers_of(msg)
    results = " ".join(v for k, v in h.items() if k in ("authentication-results", "arc-authentication-results"))
    if not results:
        return "none"
    domain = parseaddr(msg.get("from") or "")[1].rpartition("@")[2].lower()
    low = results.lower()
    if re.search(r"\bdmarc=pass\b", low):
        return "pass"
    if re.search(r"\b(?:dmarc|dkim|spf)=fail\b", low) and not re.search(r"\bdkim=pass\b", low):
        return "fail"
    for m in re.finditer(r"dkim=pass[^;]*?header\.(?:d|i)=@?([a-z0-9.-]+)", low):
        if domain and (m.group(1) == domain or domain.endswith("." + m.group(1)) or m.group(1).endswith("." + domain)):
            return "pass"
    for m in re.finditer(r"spf=pass[^;]*?smtp\.mailfrom=(?:[^@\s;]*@)?([a-z0-9.-]+)", low):
        if domain and (m.group(1) == domain or m.group(1).endswith("." + domain)):
            return "pass"
    return "none"


# ── 3. hard exclusions ─────────────────────────────────────────────────────

_EXCLUSIONS: dict[str, str] = {
    "contract": r"\b(?:contracts?|agreements?|nda|non[- ]disclosure|terms of (?:service|sale)|sign(?:ed|ature)? the|"
                r"contrats?|accord de|convention|avenant|signature|договор\w*|соглашени\w*|подпис\w*)\b",
    "legal": r"\b(?:lawyer|attorney|legal (?:action|notice)|lawsuit|court|subpoena|gdpr request|cease and desist|"
             r"avocat|mise en demeure|tribunal|huissier|contentieux|юрист\w*|адвокат\w*|суд\w*|претензи\w*)\b",
    "payment": r"\b(?:payments?|pay(?:ing)? (?:you|us|me)|invoices?|wire transfer|refund|chargeback|paypal|stripe|"
               r"paiements?|facture\w*|virement|remboursement|régler|оплат\w*|счёт\w*|счет\w*|платеж\w*|платёж\w*|возврат\w*)\b",
    "bank": r"\b(?:iban|bic|swift|bank (?:details|account)|routing number|sort code|rib|"
            r"coordonnées bancaires|relevé d'identité bancaire|банковск\w*|реквизит\w*|расчётн\w*|расчетн\w*)\b",
    # Asking about a price is ordinary business mail an acknowledgement may answer; PROMISING one
    # is not — that half is enforced on the reply (quality: money / commitment block auto-send).
    # What stays here is mail whose subject is the money itself.
    "financial": r"\b(?:deposit|loan|investment|down payment|acompte|prêt|investissement|"
                 r"кредит\w*|инвестиц\w*|предоплат\w*|залог\w*)\b",
    "employment": r"\b(?:job offer|offer of employment|salary|hiring you|employment contract|onboarding|"
                  r"offre d'emploi|promesse d'embauche|salaire|embauche|cdi|cdd|оффер\w*|зарплат\w*|трудоустройств\w*|ваканси\w*)\b",
    "government": r"\b(?:tax(?:es)? (?:office|authority|return)|irs|hmrc|urssaf|impots\.gouv|dgfip|caf|préfecture|"
                  r"administration fiscale|ants|pôle emploi|france travail|налогов\w*|госуслуг\w*|"
                  r"гос(?:ударственн)?\w* (?:орган|служб)\w*|\.gouv\.fr)\b",
    "account_recovery": r"\b(?:reset (?:your |my )?password|password reset|recover(?:y)? (?:your|my)? ?account|"
                        r"verification code|one[- ]time (?:code|password)|2fa|two[- ]factor|"
                        r"réinitialis\w* (?:le|votre) mot de passe|code de vérification|восстановлени\w*|сброс\w* парол\w*|код подтверждени\w*)\b",
    "credentials": r"\b(?:password|passcode|api key|access token|secret key|login details|credentials|"
                   r"mot de passe|identifiants|пароль|логин\w*|учётн\w* данн\w*|учетн\w* данн\w*)\b",
    "security_incident": r"\b(?:breach|hacked|compromised|phishing|malware|ransomware|vulnerability|security incident|"
                         r"unauthori[sz]ed access|piratage|piraté|compromis|fuite de données|взлом\w*|утечк\w*|фишинг\w*|уязвимост\w*)\b",
    "irreversible": r"\b(?:delete (?:my|the|your) account|close (?:my|the) account|cancel (?:my|the) subscription|"
                    r"transfer (?:the )?ownership|terminate|supprimer (?:mon|le) compte|résilier|résiliation|"
                    r"удалить (?:мой )?аккаунт|расторгнуть|расторжени\w*)\b",
}
_EXCLUSION_RE = {k: re.compile(v, re.IGNORECASE) for k, v in _EXCLUSIONS.items()}

#: Attachment types that make a message "paperwork", never small talk.
_SENSITIVE_ATTACHMENT = re.compile(
    r"\.(?:pdf|docx?|xlsx?|odt|ods|zip|rar|7z|p7m|p7s|pem|key|pfx|p12)$", re.IGNORECASE
)


@dataclass
class Exclusions:
    categories: list[str]
    evidence: dict[str, str]

    def __bool__(self) -> bool:
        return bool(self.categories)

    def summary(self) -> str:
        return ", ".join(f"{c} ({self.evidence.get(c, '')!r})" for c in self.categories)


def hard_exclusions(msg: dict[str, Any], *, extra: list[str] | None = None) -> Exclusions:
    """Every exclusion category *msg* touches. *extra* adds the policy's own review words."""
    text = " ".join(str(msg.get(k) or "") for k in ("subject", "body", "snippet"))
    cats: list[str] = []
    evidence: dict[str, str] = {}
    for name, rx in _EXCLUSION_RE.items():
        m = rx.search(text)
        if m:
            cats.append(name)
            evidence[name] = m.group(0)[:40]
    for name in msg.get("attachment_names") or []:
        if _SENSITIVE_ATTACHMENT.search(str(name)):
            cats.append("sensitive_attachment")
            evidence["sensitive_attachment"] = str(name)[:40]
            break
    else:
        if msg.get("has_attachment") and not msg.get("attachment_names"):
            cats.append("sensitive_attachment")
            evidence["sensitive_attachment"] = "an attachment"
    for word in extra or []:
        w = str(word).strip()
        if w and re.search(rf"\b{re.escape(w)}\b", text, re.IGNORECASE):
            cats.append("policy_review_word")
            evidence["policy_review_word"] = w
            break
    return Exclusions(cats, evidence)
