"""Continue this work — a portable context pack built from chosen conversations.

Give it a chat, several, or a folder; get one Markdown document another agent (Claude Code,
NAVIG's agent, a colleague) can start from:

* the sources (each chat with its link, dates, completeness and where the copy came from),
* confirmed decisions — and the superseded ones, so nobody revives an abandoned choice,
* open questions and tasks, proposals nobody confirmed,
* relevant code and references, and where each conversation left off,
* **what is missing** — incomplete copies, attachments never saved, other branches, anything
  cut to fit the budget. A pack never pretends to hold more than it does.

Every item cites ``<chat link>#navig-msg=<message id>``: one click lands on the message.
It is a snapshot (no live link back), built deterministically from the library — no model is
called, nothing leaves the computer unless the person sends the file somewhere.

It plugs into what NAVIG already has rather than adding a context system: ``--into <space>``
writes it to that space's ``.navig/plans/briefs/`` (where project tooling already looks), and
chats shared at the ``agent`` level feed the project context pack (``navig project context``).
"""

from __future__ import annotations

import json
import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from navig_chats import extract as ex
from navig_chats.export import folder_paths, role_label, safe_name

PACK_MARKER = "<!-- generated by navig chats handoff -->"
#: (section id, title, char budget). Order is the reading order.
SECTION_BUDGETS: tuple[tuple[str, str, int], ...] = (
    ("decisions", "Confirmed decisions", 6000),
    ("open", "Open questions and tasks", 4000),
    ("proposed", "Proposed, not confirmed", 2500),
    ("superseded", "Superseded decisions — do not revive", 2000),
    ("snippets", "Relevant code", 6000),
    ("recent", "Where it left off", 5000),
    ("references", "References", 1500),
)
MAX_SNIPPETS = 8
RECENT_TURNS = 4
MAX_CHATS = 200


def cite(conv: dict[str, Any], message_id: str | None) -> str:
    """A link that opens the exact message (the Dock jumps to ``#navig-msg``)."""
    if conv.get("url") and message_id:
        return f"{conv['url']}#navig-msg={message_id}"
    return conv.get("url") or f"navig chats show {conv['native_id']}"


def _when(ts: str | None) -> str:
    return (ts or "")[:10] or "undated"


def _fit(lines: list[str], budget: int) -> tuple[list[str], int]:
    """Whole lines up to ``budget`` chars; returns the kept lines and how many were dropped."""
    out, used = [], 0
    for i, line in enumerate(lines):
        if used + len(line) + 1 > budget and out:
            return out, len(lines) - i
        out.append(line)
        used += len(line) + 1
    return out, 0


def build_handoff(
    store: Any,
    ids: list[str],
    *,
    title: str | None = None,
    goal: str | None = None,
    compact: bool = False,
) -> dict[str, Any]:
    """Build the pack for ``ids``. Returns ``{markdown, title, sources, items, missing, report}``.

    ``compact`` keeps only decisions and open items (for the project context pack's budget).
    """
    missing: list[str] = []
    paths = folder_paths(store.folders())
    convs: list[dict[str, Any]] = []
    for cid in list(dict.fromkeys(ids))[:MAX_CHATS]:
        conv = store.get(cid)
        if conv is None:
            missing.append(f"`{cid}` is not in the library (removed, or never saved).")
            continue
        convs.append(conv)
    if len(dict.fromkeys(ids)) > MAX_CHATS:
        missing.append(f"Only the first {MAX_CHATS} of {len(ids)} chats were included.")
    if not convs:
        raise LookupError("none of those chats are in the library")

    items: list[ex.Item] = []
    messages_by: dict[str, list[dict[str, Any]]] = {}
    for conv in convs:
        msgs = store.messages(conv["id"])
        messages_by[conv["id"]] = msgs
        items += ex.extract(conv, msgs, conv.get("bookmarks"))
        if conv["completeness"] != "complete":
            why = {
                "rendered": "saved from the page: the branch that was on screen, without hidden tool turns",
                "partial": "partial: some messages were never saved",
                "url_only": "only the link was saved — no messages",
            }.get(conv["completeness"], conv["completeness"])
            missing.append(f"**{conv['display_title']}** — {why}. Import the ChatGPT export for the full chat.")
        if conv.get("branch_count"):
            missing.append(f"**{conv['display_title']}** — {conv['branch_count']} message(s) on other branches "
                           "(regenerated answers, edited prompts) are not in this pack.")
        lost = sum(1 for m in msgs for a in m.get("attachments") or [] if not a.get("available"))
        if lost:
            missing.append(f"**{conv['display_title']}** — {lost} attachment(s) were never in the library.")
    items = ex.resolve(items)
    by_conv = {c["id"]: c for c in convs}

    def line(it: ex.Item, text: str) -> str:
        conv = by_conv[it.conversation_id]
        who = {"marked": "marked by you", "user": "you", "assistant": "assistant"}.get(it.basis, it.basis)
        subj = f"**{it.subject}** — " if it.subject else ""
        return f"- {subj}{text} · _{who}, {_when(it.ts)}_ · [source]({cite(conv, it.message_id)})"

    sections: dict[str, list[str]] = {sid: [] for sid, _, _ in SECTION_BUDGETS}
    for it in sorted(items, key=lambda i: (i.ts or "", i.position), reverse=True):
        if it.kind == "decision":
            target = {"current": "decisions", "proposed": "proposed", "superseded": "superseded"}.get(it.status)
            if target:
                text = it.text if it.status != "superseded" else f"~~{it.text}~~ → superseded"
                sections[target].append(line(it, text))
        elif it.kind in ("task", "question") and it.status == "open":
            label = "Question" if it.kind == "question" else "Task"
            if it.basis == "assistant" and it.kind == "task":
                sections["proposed"].append(line(it, f"Suggested task: {it.text}"))
            else:
                sections["open"].append(line(it, f"{label}: {it.text}"))
    if not compact:
        snippets = [it for it in items if it.kind == "snippet"]
        marked = [it for it in snippets if it.basis == "marked"]
        recent = sorted((it for it in snippets if it.basis != "marked"), key=lambda i: (i.ts or "", i.position))[-MAX_SNIPPETS:]
        for it in (marked + list(reversed(recent)))[:MAX_SNIPPETS]:
            conv = by_conv[it.conversation_id]
            code = it.text if len(it.text) <= 1500 else it.text[:1500] + "\n# …truncated — see the source"
            sections["snippets"].append(
                f"From **{conv['display_title']}** ({'marked by you' if it.basis == 'marked' else role_label(it.role, conv['provider'])}, "
                f"{_when(it.ts)}) · [source]({cite(conv, it.message_id)})\n\n```{it.lang}\n{code}\n```\n"
            )
        for conv in convs:
            msgs = messages_by[conv["id"]][-RECENT_TURNS:]
            if not msgs:
                continue
            sections["recent"].append(f"**{conv['display_title']}**")
            for m in msgs:
                txt = re.sub(r"```.*?(```|$)", "[code]", m["text"], flags=re.S)
                txt = " ".join(txt.split())
                txt = txt if len(txt) <= 360 else txt[:359] + "…"
                sections["recent"].append(f"> **{role_label(m['role'], conv['provider'])}:** {txt} · [source]({cite(conv, m['id'])})")
            sections["recent"].append("")
        seen: set[str] = set()
        for it in items:
            if it.kind == "link" and it.text not in seen:
                seen.add(it.text)
                sections["references"].append(f"- {it.text} · [where]({cite(by_conv[it.conversation_id], it.message_id)})")

    now = datetime.now(timezone.utc).isoformat(timespec="seconds")
    folder_names = sorted({paths[f] for c in convs for f in c.get("folders") or [] if f in paths})
    heading = title or (folder_names[0] if len(folder_names) == 1 else convs[0]["display_title"] if len(convs) == 1 else f"{len(convs)} conversations")
    md = [
        PACK_MARKER,
        f"# Continue this work — {heading}",
        "",
        f"_Context pack built {now} by NAVIG from the local chat library. Every item links to the message it comes from; "
        "decisions marked by the person or stated with an explicit marker are separated from the assistant's proposals._",
        "",
    ]
    if goal:
        md += ["## Goal", goal.strip(), ""]
    md += ["## Sources", "", "| Chat | Started | Updated | Copy | Messages | Folders |", "|---|---|---|---|---|---|"]
    for c in convs:
        fl = ", ".join(paths[f] for f in c.get("folders") or [] if f in paths) or "—"
        project = f" · ChatGPT Project `{c['remote_project_id']}`" if c.get("remote_project_id") else ""
        name = c["display_title"].replace("|", "/")
        md.append(f"| [{name}]({c.get('url') or '#'}){project} | {_when(c.get('created_at'))} | {_when(c.get('updated_at'))} "
                  f"| {c['completeness']} ({c['provenance']}) | {c['message_count']} | {fl.replace('|', '/')} |")
    md.append("")
    report = []
    for sid, label, budget in SECTION_BUDGETS:
        lines = sections[sid]
        if not lines:
            report.append({"section": sid, "items": 0, "dropped": 0})
            continue
        kept, dropped = _fit(lines, budget // (3 if compact else 1))
        report.append({"section": sid, "items": len(lines), "dropped": dropped})
        if dropped:
            missing.append(f"{dropped} more item(s) under “{label}” did not fit — open the sources for the rest.")
        md += [f"## {label}", "", *kept, ""]
    md += ["## Missing or incomplete context", ""]
    md += [f"- {m}" for m in missing] or ["- Nothing known to be missing: every chat is a complete export copy."]
    md += ["", "---", "_Regenerate: `navig chats handoff " + " ".join(c["native_id"][:8] for c in convs[:5])
           + ("…" if len(convs) > 5 else "") + "` · paste or @-mention this file in Claude Code to continue._", ""]
    return {
        "title": heading,
        "built_at": now,
        "markdown": "\n".join(md),
        "sources": [{"id": c["id"], "title": c["display_title"], "url": c.get("url"), "completeness": c["completeness"]} for c in convs],
        "items": [it.to_dict() for it in items if it.kind != "link"],
        "counts": ex.summarize(items),
        "missing": missing,
        "report": report,
    }


def pack_filename(pack: dict[str, Any]) -> str:
    return f"chat-handoff-{pack['built_at'][:10]}-{safe_name(pack['title'], 60).replace(' ', '-').lower()}.md"


def write_into_space(space_root: Path, pack: dict[str, Any]) -> Path:
    """Write the pack into ``<space>/.navig/plans/briefs/`` (where project tooling reads briefs).

    Refuses to overwrite a file it did not write.
    """
    target = Path(space_root) / ".navig" / "plans" / "briefs" / pack_filename(pack)
    if target.exists() and PACK_MARKER not in target.read_text(encoding="utf-8", errors="replace")[:400]:
        raise FileExistsError(f"{target} exists and was not written by navig — not overwriting")
    target.parent.mkdir(parents=True, exist_ok=True)
    tmp = target.with_suffix(".md.part")
    tmp.write_text(pack["markdown"], encoding="utf-8", newline="\n")
    tmp.replace(target)
    return target


def pack_json(pack: dict[str, Any]) -> str:
    return json.dumps(pack, ensure_ascii=False, indent=2)


__all__ = ["PACK_MARKER", "build_handoff", "cite", "pack_filename", "pack_json", "write_into_space"]
